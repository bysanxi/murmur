const ALIAS = [];
for (const [keys, lat, lon] of ROWS) {
  for (const key of keys) {
    ALIAS.push({ key, lat, lon, len: key.length });
  }
}
ALIAS.sort((a, b) => b.len - a.len);

function haystack(name, region) {
  return `${name || ""} ${region || ""}`.toLowerCase();
}

/// Longest alias that appears in the station name or region.
export function cityCoordsOf(name, region) {
  const blob = haystack(name, region);
  if (!blob.trim()) return null;
  for (const row of ALIAS) {
    if (blob.includes(row.key.toLowerCase())) {
      return [row.lat, row.lon];
    }
  }
  return null;
}
